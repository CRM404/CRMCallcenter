// --- services/appSettings.js: чтение настроек приложения ---
//
// Зачем отдельный модуль на два запроса. Настройка — это значение, которое
// читают из РАЗНЫХ мест: рубильник автообзвона спросит дозвонщик, порог сторожа
// — сторож, срок хранения — создание полок. Если каждый напишет своё чтение,
// они разойдутся в мелочи: один сочтёт отсутствие строки выключенным, другой
// включённым, третий уронит запрос на NULL. Разойдутся не в день написания, а
// через полгода, и виноватым будет выглядеть тумблер (ответ куратора И143).
//
// КЕША ЗДЕСЬ НЕТ НАМЕРЕННО, и это тоже ответ И143. Настройка меняется человеком
// в аварии — ровно тогда, когда «через минуту подхватится» означает минуту
// работы системы вопреки нажатой кнопке. Цена отказа от кеша — один запрос по
// первичному ключу, самый дешёвый, какой бывает.

/**
 * Значение настройки как оно лежит в базе — строкой.
 *
 * Возвращает `fallback`, если строки нет ВОВСЕ или значение пустое. Это два
 * разных случая для экрана настроек, но один для читателя: и там и там система
 * работает по умолчанию из кода, и знать, чем именно вызвана пустота, читателю
 * незачем.
 */
async function get(db, key, fallback = null) {
    const found = await db.query('SELECT value FROM app_settings WHERE key = $1', [key]);
    if (found.rows.length === 0) return fallback;
    const value = found.rows[0].value;
    return value === null || value === '' ? fallback : value;
}

/**
 * Выключатель.
 *
 * ВКЛЮЧЕНО — ЭТО РОВНО СТРОКА 'true' (соглашение проекта, ответ куратора И142;
 * оно же записано у колонки value_type в schema.sql). Всё остальное — 'True',
 * '1', 'yes', мусор, пустота, отсутствие строки — читается как ВЫКЛЮЧЕНО.
 *
 * Несимметрично намеренно. Настройки этого рода разрешают системе действовать
 * самой: звонить людям, рассылать, списывать. Ошибка разбора обязана падать в
 * сторону бездействия — «не сработало» замечают и чинят, «сработало само»
 * замечают по последствиям.
 */
async function getBool(db, key, fallback = false) {
    const raw = await get(db, key, null);
    if (raw === null) return fallback;
    return raw === 'true';
}

module.exports = { get, getBool };
