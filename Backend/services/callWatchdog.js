// --- services/callWatchdog.js: сторож зависших звонков (план 7.3) -----------
//
// ЗАЧЕМ. Строка звонка живёт «активной», пока у неё пусто `ended_at`. Станция
// закрывает её событием окончания; если события не пришло — сбой на стороне
// станции, обрыв канала, перезапуск в неудачный момент, — строка остаётся
// активной НАВСЕГДА. Один такой звонок незаметен, десяток за месяц делает
// вкладку бесполезной: в ней перестают искать настоящее.
//
// ЧТО ДЕЛАЕТ. Раз в тик планировщика закрывает служебным исходом `lost`
// («связь потеряна») те строки, которые висят активными дольше порога И по
// которым не пришло НИ ОДНОГО события станции.
//
// ⚠ ПРАВИЛО ВЗЯТО ИЗ ПЛАНА ДОСЛОВНО, и у него есть узкое место, названное
// вслух: «нет НИ ОДНОГО события». Звонок, по которому событие пришло один раз,
// а потом станция замолчала, сторож не тронет. Расширять правило до «последнее
// событие старше порога» я не стал: это уже другое решение, и принимать его
// мимо владельца нельзя. Когда станция заработает и такой случай появится —
// правило меняется здесь одной строкой условия.
//
// ПОЧЕМУ СЛУЖЕБНЫЙ АВТОР. Закрытие пишется триггером аудита в журнал; без
// `runAsService` строка встала бы «не указан», то есть выглядела бы правкой из
// админки, которой никто не делал (решение владельца 98).
//
// ПОЧЕМУ НЕ ТРИГГЕР И НЕ SQL-ФУНКЦИЯ. Ровно та же причина, что у приведения
// номеров: правило времени живёт в приложении, а второй его реализацией на
// plpgsql мы получили бы два места, расходящихся в первый же день правки.

const auditContext = require('./auditContext');
const appSettings = require('./appSettings');

// ПОРОГ — ЧЕТЫРЕ ЧАСА (план 7.3, там же он назван предложенным). ТЕПЕРЬ ЭТО
// УМОЛЧАНИЕ, А НЕ ЕДИНСТВЕННОЕ МЕСТО: порог задаётся на экране настроек
// (`stale_call_hours`), а число здесь работает, пока настройку не задали, и
// когда её значение оказалось битым. Убрать константу нельзя — пустая строка
// в базе не должна ронять сторожа (ответы куратора 12 и 13).
const STALE_HOURS = 4;

/**
 * Закрыть зависшие звонки. Зовётся тиком планировщика.
 *
 * Возвращает `{ closed, ids }` — не «готово», а имена того, что снято: тик
 * пишет в журнал службы число, и по нему потом видно, был ли сбой станции.
 */
// ЧАСЫ ПРИХОДЯТ ПАРАМЕТРОМ ТОЛЬКО ЯВНО. Прежде здесь стояло умолчание
// `hours = STALE_HOURS`, и с ним настройку было не прочитать: аргумент
// всегда определён, и «звали без порога» стало бы неотличимо от «звали с
// порогом четыре». Теперь не передали — читаем настройку, передали — верим
// вызвавшему: этим пользуются проверки.
async function closeStaleCalls(pool, hours) {
    const limitHours = hours === undefined
        ? await appSettings.getInt(pool, 'stale_call_hours', STALE_HOURS)
        : hours;
    return auditContext.runAsService('Система', async () => {
        const result = await pool.query(
            `UPDATE calls c
                SET outcome = 'lost',
                    ended_at = NOW(),
                    updated_at = NOW()
              WHERE c.ended_at IS NULL
                AND c.outcome IS NULL
                AND c.started_at <= NOW() - make_interval(hours => $1::int)
                AND NOT EXISTS (
                    SELECT 1
                      FROM pbx_events e
                     WHERE c.pbx_call_id IS NOT NULL
                       AND e.pbx_call_id = c.pbx_call_id
                )
              RETURNING id`,
            [limitHours]
        );
        return { closed: result.rows.length, ids: result.rows.map((r) => r.id) };
    });
}

module.exports = { STALE_HOURS, closeStaleCalls };
