// --- services/eventChannel.js: живой канал сервер → браузер (часть 6, В3) ---
//
// ДО ЭТОЙ ЧАСТИ БРАУЗЕР УЗНАВАЛ НОВОСТИ, ТОЛЬКО КОГДА САМ СПРАШИВАЛ. Для
// телефонии это не годится: у Телфина часовой лимит запросов на все приложения
// клиента, и панель, живущая на опросе, съест его на пустых ответах (план 14).
//
// SSE, А НЕ WEBSOCKET (ответ куратора И41). WebSocket требует библиотеки, SSE не
// требует ничего: это обычный HTTP-ответ, который не закрывают. Направление нам
// нужно ровно одно — от сервера к браузеру.
//
// ЧТО ЗДЕСЬ ЕСТЬ И ЧЕГО НЕТ. Есть труба и ОДНО настоящее событие — «лид
// отправлен в архив». Оно уже происходит: часть 5Б в бою. Труба, по которой ни
// разу не проехал настоящий груз, проверена не будет, а придуманный `ping`
// доказывает только сам себя (ответ куратора И119).
//
// Потребитель появился частью 7Б: вкладка «Активные» раздела «Звонки» слушает
// канал вместо опроса (Calls/js/modules/callsApp.js, openLiveChannel).
//
// ---------------------------------------------------------------------------
// СЛОВАРЬ СОБЫТИЙ. ЕДИНСТВЕННОЕ МЕСТО, ГДЕ ОНИ ВИДНЫ ВСЕ СРАЗУ (ответ куратора
// И180): имена даёт куратор, записывает исполнитель, новое дописывается СЮДА, а
// не берётся из головы. Разошедшиеся имена — это отправитель, который шлёт в
// пустоту, и подписчик, который ждёт того, чего не будет; ошибки при этом нет
// нигде, и искать её нечем.
//
//   lead:archived   — лид отправлен в архив (часть 5Б). Шлёт routes/leadsAdmin.
//   operator:state  — оператор сменил состояние (часть 7Б). Шлёт сервер из
//                     services/operatorState.js, а не браузер оператора: панель
//                     сообщила о себе обычным запросом, кому это интересно —
//                     забота сервера (И181).
//   call:started    — начался разговор. ЖДЁТ ТЕЛЕФОНИИ: отправителя сегодня нет
//                     вовсе, появится вместе с приёмником событий станции
//                     (этап Е). Имя записано заранее намеренно — чтобы к тому
//                     дню его не придумывали заново.
//   call:ended      — разговор завершён. Там же и тогда же.
//
// Отправитель есть сегодня у двух: `lead:archived` и `operator:state`. Два
// звонковых молчат до этапа Е — это не дефект, а порядок частей.
// ---------------------------------------------------------------------------
//
// КАНАЛ ОТКРЫТ ТАК ЖЕ, КАК ОСТАЛЬНОЕ API, И ЭТО НАЗВАНО ВСЛУХ (ответ И137).
// Входа у руководителя в приложении нет вовсе: все админские маршруты отвечают
// без авторизации. Городить проверку на одном канале, когда рядом открыто всё
// остальное, — самообман: закрывать надо целиком и вместе с настоящим входом
// (бриф, Д6).

// Сердцебиение. Прокси на бою рвёт молчащее соединение по
// `proxy_read_timeout 300s` (замер куратора, ответ И139) — двоеточие раз в
// 25 секунд держит канал живым с большим запасом. Строка, начинающаяся с
// двоеточия, — комментарий формата SSE: браузер её не видит, но она едет по
// сети и обнуляет таймер молчания.
const HEARTBEAT_MS = 25 * 1000;

const clients = new Set();
let beat = null;

/**
 * Подписка. Ответ не закрывается — это и есть канал.
 *
 * Заголовки:
 *  - `text/event-stream` — иначе браузер прочтёт это как обычный ответ;
 *  - `no-cache, no-transform` — чтобы посредники не собирали поток в буфер;
 *  - `X-Accel-Buffering: no` — на бою `proxy_buffering off` уже стоит в конфиге
 *    nginx (проверено куратором), но заголовок ставится всё равно: он дешёвый и
 *    переживёт смену конфига, а без буферизации-выключателя события приходят
 *    пачками по несколько минут, и выглядит это как «канал не работает».
 */
function subscribe(req, res) {
    res.writeHead(200, {
        'Content-Type': 'text/event-stream; charset=utf-8',
        'Cache-Control': 'no-cache, no-transform',
        Connection: 'keep-alive',
        'X-Accel-Buffering': 'no'
    });
    // Первая строка уходит немедленно: до неё браузер не считает подписку
    // состоявшейся, а `EventSource.onopen` не сработает.
    res.write(': подписка открыта\n\n');
    if (typeof res.flushHeaders === 'function') res.flushHeaders();

    clients.add(res);
    // Уходит и по закрытию вкладки, и по обрыву сети. Без снятия множество
    // подписчиков растёт до перезапуска, и каждое событие пишется в мёртвые
    // сокеты.
    req.on('close', () => { clients.delete(res); });
}

/**
 * Отправить событие всем подписчикам.
 *
 * ПОЛЕЗНОЙ НАГРУЗКОЙ ЕДУТ ТОЛЬКО ИДЕНТИФИКАТОРЫ И ВРЕМЯ. Канал открыт, и класть
 * в него телефон или имя значит раздавать их всякому, кто открыл адрес. Кому
 * нужны подробности — спросит их обычным запросом, там же, где и раньше.
 *
 * Ошибка записи в один сокет не должна ронять рассылку остальным: сокет,
 * который уже закрылся, просто выкидывается из множества.
 */
function publish(name, data) {
    if (clients.size === 0) return 0;
    const payload = `event: ${name}\ndata: ${JSON.stringify(data)}\n\n`;
    let sent = 0;
    for (const res of [...clients]) {
        try {
            res.write(payload);
            sent++;
        } catch (err) {
            clients.delete(res);
        }
    }
    return sent;
}

/** Сколько подписчиков сейчас. Нужно проверкам и разбору происшествий. */
function subscriberCount() {
    return clients.size;
}

/**
 * Сердцебиение живёт СВОИМ таймером, а не тиком планировщика (ответ куратора
 * И139): планировщик по умолчанию выключен, а канал обязан работать и без него.
 */
function start() {
    if (beat) return;
    beat = setInterval(() => {
        for (const res of [...clients]) {
            try { res.write(': жив\n\n'); } catch (err) { clients.delete(res); }
        }
    }, HEARTBEAT_MS);
}

function stop() {
    if (beat) {
        clearInterval(beat);
        beat = null;
    }
    for (const res of [...clients]) {
        try { res.end(); } catch (err) { /* уже закрыт */ }
    }
    clients.clear();
}

module.exports = { subscribe, publish, subscriberCount, start, stop, HEARTBEAT_MS };
