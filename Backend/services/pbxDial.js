// --- services/pbxDial.js: исходящий звонок из CRM (этап Е2) ------------------
//
// ЗАЧЕМ ОТДЕЛЬНАЯ СЛУЖБА, А НЕ ТЕЛО МАРШРУТА. Ровно та же причина, по которой
// приём событий живёт в `pbxEventStore.js`: набор — это четыре разных решения
// подряд (можно ли звонить, кем звонить, куда звонить, что записать), и каждое
// из них проверяется отдельно. В теле маршрута они слиплись бы в одну лестницу
// `if`, а приёмке пришлось бы поднимать HTTP ради проверки разбора номера.
//
// ⛔⛔ ЭТО ПЕРВОЕ МЕСТО ПРОЕКТА, КОТОРОЕ ДЕЙСТВУЕТ В ЧУЖОМ МИРЕ. Всё, что было
// до сих пор, меняло нашу базу; здесь у живого человека звонит телефон. Отсюда
// два правила, которых нет больше нигде:
//   · повтор запроса запрещён (см. `apiPost` в `services/pbxClient.js`);
//   · отказ станции показывается человеку ТЕКСТОМ, а не глотается (решение
//     владельца 147): «ничего не произошло» — худший из возможных ответов, если
//     где-то в этот момент мог зазвонить телефон.
//
// ⚠⚠ СТАНЦИЯ ЗВОНИТ СНАЧАЛА ОПЕРАТОРУ, И ЭТО МЕНЯЕТ СМЫСЛ УСПЕХА. Порядок
// `callback` прямой: сначала вызов на `src_num` — добавочный оператора, — и
// только после снятия там трубки идёт вызов клиенту. Значит удачный ответ
// станции означает «набор принят», а НЕ «состоялся разговор»: ответил ли
// оператор, узнаем событием `hangup`. Поэтому `answered` здесь не ставится
// вовсе — его ставит разбор (`pbxEventStore.js`), и другого источника у него
// нет.
//
// ⚠ ЧЕГО В ЗАПРОСЕ НЕТ НАМЕРЕННО, И ЭТО СТОИТ ПРОВЕРИТЬ ПЕРВОЙ ПРОБОЙ:
// `autoanswer_src`. План (раздел Е2) говорит «поднимает трубку оператора сама»,
// паспорт Телфина в рекомендуемом составе показывает `variables:
// {autoanswer_src: "0", tag: "<lead_id>"}` — но что означает "0", включение или
// выключение, ни один из двух источников не говорит. Наряд куратора от
// 04.09.2026 перечисляет состав запроса поимённо и этого параметра НЕ называет.
// Взято по наряду: параметр, смысла значения которого мы не знаем, в первый
// живой звонок не отправляется. Трубка у оператора зазвонит — по решению 146
// первую проверку делает владелец лично, с работающим софтфоном.

const pbxClient = require('./pbxClient');
const appSettings = require('./appSettings');
const phoneFormat = require('./phoneFormat');

// ДЛИНА ВНУТРЕННЕГО НОМЕРА — ЗАМЕР СТАНЦИИ, А НЕ ДОГАДКА (решение владельца
// 147): `GET /client/84092/client/` отдаёт префикс `16780` и длину 3. Число
// стоит здесь одно и с именем: три в коде набора без имени однажды прочтут как
// «три первые цифры».
const INTERNAL_LEN = 3;

/** Ошибка с кодом — маршрут по коду выбирает и статус, и текст. */
function fail(code, message) {
    const err = new Error(message);
    err.code = code;
    return err;
}

// ---------------------------------------------------------------- номер
//
// ДВА ВИДА НОМЕРА В ОДНОМ ПОЛЕ (решение владельца 147). Внутренний уходит как
// есть, тремя цифрами; внешний приводится к единому виду ОБЩЕЙ функцией
// (`services/phoneFormat.js`) — своего приведения здесь нет и не будет: третий
// вид показа телефона мы уже завели отдельной задачей (56), четвёртый заводить
// незачем.
//
// ⚠ РАЗЛИЧАЮТСЯ ПО ЧИСЛУ ЦИФР, А НЕ ПО ВИДУ СТРОКИ. «101» и «+7 (101)» — это
// 3 и 4 цифры: маска пульта второй случай не создаёт, но сервер судит сам, и
// судит по тому, что до него доехало.
function parseTarget(raw) {
    const text = raw === null || raw === undefined ? '' : String(raw).trim();
    const digits = text.replace(/\D/g, '');

    if (digits.length === INTERNAL_LEN) {
        return { dst: digits, internal: true, reason: null };
    }

    const norm = phoneFormat.normalizePhone(text);
    if (norm.reason) return { dst: null, internal: false, reason: norm.reason };
    return { dst: norm.phone, internal: false, reason: null };
}

// ---------------------------------------------------------------- набор
//
// ПОРЯДОК ШАГОВ ЗДЕСЬ — ЧАСТЬ УСТРОЙСТВА, А НЕ УДОБСТВО ЧТЕНИЯ.
//
//   1. рубильник      — прежде всего прочего: выключенный набор не должен даже
//                       читать карточку сотрудника;
//   2. сотрудник      — от него добавочный, и без него звонить нечем;
//   3. номер          — разбирается ДО обращения к станции: негодный номер не
//                       стоит запроса из часового лимита;
//   4. станция        — единственный необратимый шаг;
//   5. запись строки  — ПОСЛЕ станции, потому что `pbx_call_id` до неё не
//                       существует.
//
// ⚠⚠ ШАГ 5 МОЖЕТ УПАСТЬ, КОГДА ЗВОНОК УЖЕ ИДЁТ, и это названо вслух: телефон
// уже звонит, отменить нечем. Тогда мы НЕ выдаём отказ — набор-то состоялся, —
// а жалуемся в журнал и отвечаем как есть. Строку в этом случае заведёт разбор
// события `hangup`, только без привязки к лиду: она была нашим знанием, а не
// станции.
async function dial(db, { employeeId, number, leadId = null }) {
    // 1 · Рубильник. ⚠⚠ УМОЛЧАНИЕ ВЫКЛЮЧЕНО — ОБРАТНО ПРИЁМУ СОБЫТИЙ, и это
    // решение наряда, а не описка. У приёма опасно БЕЗДЕЙСТВИЕ: выключенный
    // приём молча теряет звонки. Здесь опасно ДЕЙСТВИЕ: свежая выкатка не имеет
    // права сама звонить живым людям, а «не сработало» замечают и включают.
    const allowed = await appSettings.getBool(db, 'pbx_dial_enabled', false);
    if (!allowed) {
        throw fail('dial_disabled', 'Исходящие звонки из CRM выключены в настройках');
    }

    // 2 · Кто звонит.
    const id = Number(employeeId);
    if (!Number.isInteger(id) || id <= 0) {
        throw fail('bad_employee', 'Не указан сотрудник');
    }
    const found = await db.query(
        'SELECT id, pbx_extension, pbx_extension_id FROM employees WHERE id = $1', [id]);
    const person = found.rows[0];
    if (!person) throw fail('employee_not_found', 'Сотрудник не найден');

    // ⛔ ДВА РАЗНЫХ ПУСТО, И ДВА РАЗНЫХ ОТВЕТА. Добавочного нет — это дело
    // руководителя, он вписывается в карточке. `pbx_extension_id` нет — это
    // наше: колонку заполняет служба при старте (`syncExtensionIds`), человеку
    // её не видно и вписать нечем. Один общий текст на оба случая отправил бы
    // человека чинить не то.
    if (!person.pbx_extension) {
        throw fail('no_extension',
            'У сотрудника не указан добавочный номер — звонить неоткуда');
    }
    if (!person.pbx_extension_id) {
        throw fail('no_extension_id',
            'Станция ещё не сопоставила добавочный сотрудника — набор невозможен');
    }

    // 3 · Куда звоним.
    const target = parseTarget(number);
    if (target.reason) {
        throw fail('bad_number', 'Номер не разобран: ' + target.reason);
    }

    // Лид проверяется ДО звонка: внешний ключ упал бы уже ПОСЛЕ него, когда
    // отменять нечего.
    let lead = null;
    if (leadId !== null && leadId !== undefined && leadId !== '') {
        const num = Number(leadId);
        if (!Number.isInteger(num) || num <= 0) throw fail('bad_lead', 'Неверный номер лида');
        const row = await db.query('SELECT id FROM leads WHERE id = $1', [num]);
        if (!row.rows.length) throw fail('lead_not_found', 'Лид не найден');
        lead = num;
    }

    // 4 · Станция. ⚠ СОСТАВ ЗАПРОСА — ПО НАРЯДУ 04.09.2026, ПОИМЁННО:
    //   `src_num` массивом из ОДНОГО добавочного — список у станции про очередь,
    //     а очереди у нас нет;
    //   `caller_id_*` равны `dst_num` — рекомендация паспорта (стр. 521):
    //     оператор видит на аппарате клиента и может перезвонить кнопкой
    //     повтора, не заходя в CRM;
    //   `variables.tag` — идентификатор лида, он же `Tag` во всех событиях
    //     вызова. Это одно поле с двух сторон, а не два разных.
    // ⛔ `src_ani`/`dst_ani`, `wait_for_pickup`, `call_duration`,
    //   `callback_rate_limit` НЕ ставятся: у первых нет списка DID (чужой номер
    //   станция молча игнорирует — получим тишину вместо ошибки), остальные —
    //   решения владельца и этап Е4.
    const body = {
        dst_num: target.dst,
        src_num: [String(person.pbx_extension)],
        caller_id_name: target.dst,
        caller_id_number: target.dst
    };
    if (lead !== null) body.variables = { tag: String(lead) };

    const answer = await pbxClient.apiPost(
        db, `/extension/${encodeURIComponent(person.pbx_extension_id)}/callback/`, body);

    const pbxCallId = answer && answer.call_id ? String(answer.call_id) : null;
    const pbxApiId = answer && answer.call_api_id ? String(answer.call_api_id) : null;

    // ⚠ СТАНЦИЯ ОТВЕТИЛА, НО БЕЗ КОРНЯ ВЫЗОВА. Такого в документации нет, но
    // ответ приходит из чужого мира: без `call_id` событию не по чему найти
    // нашу строку, и склеивать её «по времени и номеру» мы отказались ещё в
    // плане. Говорим об этом, а не делаем вид, что всё в порядке.
    if (!pbxCallId) {
        throw fail('no_call_id',
            'Станция приняла набор, но не вернула идентификатор вызова');
    }

    // 5 · Наша строка. АВТОР ПРАВКИ — ОПЕРАТОР, А НЕ СЛУЖБА, и подписи здесь
    // нет намеренно: запрос пришёл со страницы оператора, а `auditContext`
    // положил его в контекст соединения ещё в middleware. `runAsService` затёр
    // бы живого человека словом «Телефония».
    //
    // ⚠ `started_at` — время НАБОРА, а не разговора: другого времени у нас в
    // эту секунду нет, и разбор события его не переписывает (`UPDATE` в
    // `pbxEventStore.js` этой колонки не касается вовсе).
    try {
        const created = await db.query(
            `INSERT INTO calls
                (pbx_call_id, pbx_api_id, direction, client_phone,
                 lead_id, employee_id, operator_extension, is_internal, started_at)
             VALUES ($1, $2, 'out', $3, $4, $5, $6, $7, NOW())
             RETURNING id`,
            [pbxCallId, pbxApiId, target.dst, lead, person.id,
                String(person.pbx_extension), target.internal]);
        return {
            id: created.rows[0].id,
            pbxCallId,
            pbxApiId,
            internal: target.internal,
            stored: true
        };
    } catch (err) {
        console.error('Телефония: набор состоялся, строка звонка не записана —',
            err && err.code);
        return { id: null, pbxCallId, pbxApiId, internal: target.internal, stored: false };
    }
}

module.exports = { dial, parseTarget, INTERNAL_LEN };
