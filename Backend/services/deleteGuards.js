// --- services/deleteGuards.js: почему удалить нельзя, и это отдаётся структурой ---
//
// Требование паспорта Р7, и оно жёсткое: сервер отдаёт СПИСОК ПАР «сколько —
// чего», а текст окна собирает экран. Иначе склонение и перевод оказываются в
// бэкенде, а список — неразбираемым для того, кто будет собирать окно.
//
// ЧТО ИМЕННО ЕДЕТ НАРУЖУ (ответ куратора И75). Не одно поле, а два:
//
//   kind — машинный код помехи ('leads', 'sources', …). По нему экран
//          подставляет своё слово, склоняет его сам и решает, показывать ли
//          ссылку «посмотреть».
//   what — то же самое словом, в именительном множественного числа.
//
// Второе поле нужно не экрану, а всем остальным: старому интерфейсу, который
// про kind не знает, журналу и человеку, читающему ответ глазами. Отдать один
// kind значит заставить каждого нового потребителя завести у себя копию
// словаря; отдать один what — вернуть перевод и склонение на сервер. Отдаём оба
// и оставляем выбор за тем, кто читает.
//
// ИДЕНТИФИКАТОРЫ ПЕРВЫХ ДЕСЯТИ (ответ куратора И76). Человек, увидев
// «привязано 4 лида», пойдёт их искать руками — и без списка искать ему нечем.
// Рядом с ids едет hasMore: десять штук без пометки читаются как «всего
// десять», и одиннадцатый человек будет искать вручную, уверенный, что его нет.
//
// ПОРЯДОК СТРОК — ФИКСИРОВАННЫЙ ПО ВИДУ, а не по числу (ответ куратора И77).
// Сортировка числом поставила бы «300 строк пула раздачи» выше «2 лида», то
// есть подняла бы наверх самое неважное. Внутри одного вида — по числу.

const auditContext = require('./auditContext');
const { withTransaction } = require('./dbTx');

// Порядок — от невосполнимого к восполнимому. Он и есть «от тяжёлого к
// лёгкому» из паспорта: тяжесть здесь не в количестве, а в том, что потеряется
// навсегда. Новый вид помехи дописывается В НУЖНОЕ МЕСТО списка, а не в конец.
//
// 'calls' стоял здесь заранее, местом под будущую таблицу. Часть 7А её завела,
// и место занято по назначению: лид со звонками не удаляется вовсе, только
// архивируется (план 11.4).
const KIND_ORDER = [
    'documents',      // сканы: в журнал не пишутся вовсе, потеря окончательна
    'calls',          // лид со звонками не удаляется вовсе
    'schedule_days',
    'leads',
    'merged_leads',
    'offers',
    'sources',
    'cpa_networks',
    'departments',
    'bank_accounts',
    'taxes'
];

// Слово в ИМЕНИТЕЛЬНОМ МНОЖЕСТВЕННОГО. Не «4 лида», а «лиды»: число едет
// отдельным полем, и склеивать их здесь значит выбирать за экран падеж.
const KIND_TITLE = {
    documents: 'документы',
    calls: 'звонки',
    schedule_days: 'дни графика',
    leads: 'лиды',
    // «ВЛИТЫЕ», А НЕ «СЛИТЫЕ» (К184). Паспорт Р7 везде пишет «влитые
    // дубли», и это же слово стоит в соседнем файле: лид «влит в
    // старшего». Окно берёт своё слово по kind и разнобоя не покажет, а
    // вот тост в пяти разделах возьмёт это — и один случай назвался бы
    // двумя словами в одном интерфейсе.
    merged_leads: 'влитые дубли',
    offers: 'объекты недвижимости',
    sources: 'источники',
    cpa_networks: 'CPA-сети',
    departments: 'отделы',
    bank_accounts: 'банковские счета',
    taxes: 'налоги'
};

const SHOWN_IDS = 10;

/**
 * Считает одну помеху. tail — всё, что идёт после SELECT: FROM, WHERE, ORDER BY.
 * Запрос обязан отдавать колонку id.
 *
 * Одним запросом, а не двумя: count(*) OVER () считается ДО LIMIT, поэтому
 * общее число и первые десять идентификаторов приезжают вместе. Два отдельных
 * запроса дали бы расхождение между числом и списком, если между ними что-то
 * поменялось, — а показывать «4» рядом со списком из пяти нельзя.
 */
async function countBlocker(db, kind, tail, params) {
    const result = await db.query(
        `SELECT count(*) OVER ()::int AS total, id ${tail} LIMIT ${SHOWN_IDS}`, params);
    if (result.rows.length === 0) return null;
    const total = result.rows[0].total;
    return {
        kind,
        what: KIND_TITLE[kind] || kind,
        count: total,
        ids: result.rows.map((r) => r.id),
        hasMore: total > result.rows.length
    };
}

/** Убирает пустые помехи и раскладывает оставшиеся в назначенном порядке. */
function orderBlockers(list) {
    return list
        .filter(Boolean)
        .sort((a, b) => {
            const ra = KIND_ORDER.indexOf(a.kind);
            const rb = KIND_ORDER.indexOf(b.kind);
            if (ra !== rb) return (ra < 0 ? KIND_ORDER.length : ra) - (rb < 0 ? KIND_ORDER.length : rb);
            return b.count - a.count;
        });
}

/**
 * Человеческая строка рядом со структурой.
 *
 * ЗАЧЕМ ОНА ВООБЩЕ, если текст собирает экран (Б3.4): экрана ещё нет, а
 * интерфейс, который зовёт удаление сегодня, показывает поле error тостом. Без
 * этой строки он показал бы «Произошла ошибка на сервере» — то есть ровно то,
 * от чего часть уходит.
 *
 * СКЛОНЕНИЯ ЗДЕСЬ НЕТ И НЕ БУДЕТ. Пример из брифа — «привязано 4 лида» —
 * требует согласовать существительное с числом, а это три формы на каждое
 * слово и то самое, что паспорт запрещает держать на сервере. Поэтому число
 * стоит рядом со словом, а не внутри фразы: «лиды — 4». Читается так же
 * понятно, а падеж выбирать не приходится.
 */
function blockersToText(blockers) {
    return 'Нельзя удалить: ' + blockers.map((b) => `${b.what} — ${b.count}`).join(', ');
}

/**
 * Ответ отказа. 409, а не 400: это конфликт с состоянием данных, а не кривой
 * запрос. Прежние отказы отвечали кто чем — 409 у CPA-сети и 400 у лида, — и
 * разнобой пришлось бы разбирать тому, кто будет собирать окно.
 */
function refuse(res, blockers) {
    return res.status(409).json({
        error: blockersToText(blockers),
        code: 'delete_blocked',
        blockers
    });
}

/**
 * Удаление с каскадом — ОДНОЙ ПАРТИЕЙ (ответ куратора И93).
 *
 * Часть 3 повесила триггер на каждую таблицу, и каскад теперь пишется в журнал
 * целиком: удалили сеть — в журнале появились её объекты, у каждого сегменты,
 * география, способы оплаты и виды ипотеки. Это и было целью (план 11.5,
 * «любое удаление становится восстановимым»), но без партии одно нажатие
 * читается как два десятка не связанных между собой записей.
 *
 * Автор строк журнала здесь служебный, а автор партии — человек: тот же
 * порядок, что у импорта (часть 3) и слияния (часть 4). Партия отвечает на
 * вопрос «кто это затеял», строки — на вопрос «что именно произошло».
 */
function deleteAsBatch(pool, title, fn) {
    return auditContext.runAsBatch(pool, { kind: 'delete', title, actorName: title },
        () => withTransaction(pool, fn));
}

module.exports = {
    countBlocker,
    orderBlockers,
    blockersToText,
    refuse,
    deleteAsBatch,
    KIND_ORDER,
    KIND_TITLE
};
