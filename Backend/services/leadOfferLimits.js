// --- services/leadOfferLimits.js: общий потолок на число офферов у лида ---
// Живёт отдельным модулем, потому что нужен двум роутам сразу и обязан у них
// совпадать: routes/realEstateOffers.js отбивает «Добавить все» на слишком
// широком отборе, routes/leadsAdmin.js — сохранение такого набора (в том числе
// в обход UI). Разъехавшиеся константы дали бы «кнопка сработала, а сохранение
// упало» (dialog.md, D2).

// Офферов в базе ≈38 000. Без потолка «Добавить все» на неотфильтрованном
// отборе привязало бы к одному лиду весь справочник, а массовая загрузка
// умножила бы это на число строк файла.
const MAX_OFFERS_PER_LEAD = 1000;

// Потолок на ПАРТИЮ: в bulk-import связки перемножаются (строки файла ×
// офферы), поэтому проверки «не больше 1000 офферов на лида» недостаточно —
// она пропускает 5000 строк × 1000 офферов = 5 млн строк в одной транзакции.
// Число — по замеру куратора на реальной базе: 200 000 связок ≈ 6 секунд,
// с запасом до таймаута прокси Railway (5000 строк × 1000 офферов давали
// ~2,5 минуты и откат всей загрузки в конце).
const MAX_OFFER_LINKS_PER_BATCH = 200000;

const TOO_MANY_OFFERS_HINT = 'Сузьте отбор фильтрами или поиском';

module.exports = { MAX_OFFERS_PER_LEAD, MAX_OFFER_LINKS_PER_BATCH, TOO_MANY_OFFERS_HINT };
