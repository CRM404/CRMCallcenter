// каждого события, оно нашлось бы через месяц по кривому отчёту, и виноватой
// выглядела бы АТС.
//
// ТРИ ЛОВУШКИ, РАДИ КОТОРЫХ ЭТО НАПИСАНО (план 4.4):
//
//   1. `EventTime` в событиях — МИКРОСЕКУНДЫ с 1 января 1970 года. Не
//      миллисекунды. Прочитанное как миллисекунды даёт 58 271 год.
//   2. `Duration` и `BridgedDuration` — тоже микросекунды. Разговор в пять
//      минут, прочитанный как миллисекунды, превращается в пять минут делить на
//      тысячу, то есть в ноль, и «разговоров не было» станет нормой отчёта.
//   3. История вызовов (`/call_history/`) отдаёт время в UTC строкой. У нас всё
//      считается в Europe/Moscow через services/appTime.js, а колонки —
//      TIMESTAMP без пояса.
//
// ЧТО ЭТОТ МОДУЛЬ ОТДАЁТ. Абсолютный момент (JS Date) и целые секунды. Дальше
// момент уходит в запрос параметром с явным `$n::timestamptz` — ровно так, как
// это описано в шапке appTime.js: Postgres сам переведёт его в пояс сессии, то
// есть в тот же вид, в котором колонки хранят NOW().
//
// ПОЧЕМУ NUMBER, А НЕ BIGINT. Микросекунды текущего времени — это примерно
// 1.79e15, а точность целых в JS кончается на 9.007e15 (2^53). Запас — до
// 2255 года. Городить BigInt ради этого незачем, но знать причину надо: если
// когда-нибудь придут наносекунды, разговор будет другим.

/** Строка или число в целое, иначе null. Пустое, мусор и Infinity — тоже null. */
function toFiniteNumber(value) {
    if (value === null || value === undefined || value === '') return null;
    const n = typeof value === 'number' ? value : Number(String(value).trim());
    return Number.isFinite(n) ? n : null;
}

/**
 * Момент события из микросекунд.
 *
 * Отрицательное и ноль считаем отсутствием времени, а не 1970 годом: у события
 * без времени поле приходит пустым или нулевым, и записывать «начало эпохи»
 * значит утверждать то, чего станция не говорила.
 */
function fromMicros(micros) {
    const n = toFiniteNumber(micros);
    if (n === null || n <= 0) return null;
    return new Date(Math.round(n / 1000));
}

/**
 * Длительность из микросекунд в ЦЕЛЫЕ СЕКУНДЫ.
 *
 * Округление, а не отбрасывание: разговор 4.6 секунды — это пять, а не четыре.
 * Ноль остаётся нулём и означает «не было», а не «неизвестно»: у станции это
 * разные вещи, и отсутствующее поле вернётся как null.
 */
function durationSeconds(micros) {
    const n = toFiniteNumber(micros);
    if (n === null || n < 0) return null;
    return Math.round(n / 1000000);
}

/**
 * Время из истории вызовов: строка в UTC.
 *
 * `Z` дописывается, если станция его не прислала. Без этого JS прочитает строку
 * как МЕСТНОЕ время, и на боевом сервере в UTC разницы не будет видно вовсе —
 * а на машине разработчика в UTC+3 всё поедет на три часа. Ошибка, которая
 * прячется ровно там, где её будут искать.
 */
function fromUtcString(text) {
    if (text === null || text === undefined || text === '') return null;
    const raw = String(text).trim();
    if (!raw) return null;
    const normalized = /[zZ]$|[+-]\d{2}:?\d{2}$/.test(raw)
        ? raw.replace(' ', 'T')
        : raw.replace(' ', 'T') + 'Z';
    const date = new Date(normalized);
    return Number.isNaN(date.getTime()) ? null : date;
}

/**
 * Обратно в микросекунды — для запросов к станции, которая их и ждёт.
 * Нужна там, где мы просим историю за период своими границами.
 */
function toMicros(date) {
    if (!(date instanceof Date) || Number.isNaN(date.getTime())) return null;
    return date.getTime() * 1000;
}

module.exports = { fromMicros, durationSeconds, fromUtcString, toMicros };
