// ДО ЭТОЙ ЧАСТИ В ПРОЕКТЕ НЕ БЫЛО НИЧЕГО, ЧТО ДЕЛАЕТ ЧТО-ЛИБО ПО ВРЕМЕНИ.
// Проверено на `main d387394`: ни одного `setInterval` вне папок разделов.
//
// И это не пустое место, а дыра. Раздачу зовут ТОЛЬКО события: сотрудник вышел
// на линию (`routes/employees.js:906,932`), лид вернулся из архива и загрузка
// партии (`routes/leadsAdmin.js:1131,1375`). А условие очереди включает
// наступивший перезвон — `next_call_at IS NOT NULL AND next_call_at <= NOW()`
// (`services/leadDistribution.js:55-61`). Значит лид, которому обещали
// перезвонить в 14:00, ждёт, пока его разбудит чужое событие: если в этот час
// никто не вышел на линию и не загрузил базу — не разбудит никто (ответ
// куратора И120).
//
// БЕЗ БИБЛИОТЕК. `setInterval` в процессе плюс замок в базе — размен, у которого
// ноль зависимостей (ответ куратора И40). Библиотека расписаний умеет больше, но
// «раз в минуту» она умеет ровно так же.
//
// ОДИН ТИК НА ВСЮ УСТАНОВКУ. Замок — `pg_try_advisory_lock`, число взято из
// реестра замков в `schema.sql`. Лишний экземпляр молча простаивает: не ошибка,
// не запись в журнал, просто ничего. Два процесса, звонящих одному лиду, —
// ровно то, что этот замок и предотвращает (план В2.4).

const { distributePendingLeads } = require('./leadDistribution');
const { closeAbandonedWrapups } = require('./callWrapup');
const { closeStaleCalls } = require('./callWatchdog');

// Раз в минуту. Шаг выбран под самую частую задачу — наступивший перезвон:
// минута опоздания незаметна человеку и не заметна базе.
const TICK_MS = 60 * 1000;

// Реестр замков ведётся в schema.sql. Строкой, а не числом: 4 826 115 501 не
// помещается в int4, и Postgres должен получить его как bigint явно, иначе
// вывод типа параметра упрётся в int4 и запрос упадёт.
const LOCK_ID = '4826115501';

let timer = null;
let current = null;     // обещание текущего тика — его дожидается остановка
let stopping = false;

/**
 * Планировщик включается ЯВНО и по умолчанию выключен.
 *
 * Довод тот же, что у рубильника автообзвона: свежая установка сама ничего не
 * делает. Плюс своя причина — установок сегодня две. Railway поднят с копией
 * тех же данных; база у него своя, значит и замок свой, и без выключателя он
 * тикал бы сам по себе, раздавая лидов в копии (ответ куратора И133).
 */
function isEnabled() {
    return process.env.SCHEDULER_ENABLED === 'true';
}

/**
 * Один проход. Никогда не бросает наружу: неотловленная ошибка в обработчике
 * таймера роняет процесс целиком, а планировщик — не то, ради чего стоит
 * останавливать сервер.
 */
async function tick(pool) {
    // Остановка уже начата — новый проход не начинаем.
    //
    // ЗАЩИТА ОТ НАЛОЖЕНИЯ ПРОХОДОВ СТОИТ НЕ ЗДЕСЬ, А В `start` (К193). Раздача
    // на большой очереди может занять больше минуты, и накладывать проходы друг
    // на друга незачем: замок защищает от чужого процесса, от самих себя —
    // признак `current`. Прежний комментарий обещал эту защиту здесь, а в коде
    // её не было вовсе.
    if (stopping) return;

    let client;
    try {
        client = await pool.connect();
        const got = await client.query('SELECT pg_try_advisory_lock($1::bigint) AS ok', [LOCK_ID]);
        // Замок занят другим экземпляром. Молча выходим: это штатное состояние
        // второй установки, а не происшествие.
        if (!got.rows[0].ok) return;

        try {
            // БРОШЕННЫЕ КАРТОЧКИ — ПЕРЕД РАЗДАЧЕЙ (часть 9, заход 5). Оператор
            // закрыл вкладку с открытой карточкой: без этого прохода `opened_at`
            // остался бы навсегда, лид не вернулся бы в очередь и не достался
            // никому. Закрытые здесь лиды раздача тем же тиком и разберёт —
            // порядок не косметика.
            //
            // Тика в минуту достаточно: этот проход ЧИНИТ БРОШЕННОЕ, а не ведёт
            // счёт. Тридцать секунд пост-обработки закроет браузер оператора
            // ровно через тридцать; сюда попадает только то, за чем никто не
            // следит.
            const closed = await closeAbandonedWrapups(pool);
            if (closed.length > 0) {
                console.log(`Планировщик: закрыто брошенных карточек — ${closed.length}`);
            }

            // СТОРОЖ ЗАВИСШИХ ЗВОНКОВ — ПЕРЕД РАЗДАЧЕЙ И ПОСЛЕ БРОШЕННЫХ
            // КАРТОЧЕК (план 7.3). Он дешёвый: одна правка по индексу, ничего
            // не читает построчно. Порядок значения не имеет — работы
            // независимы, — но раздача самая долгая, и ставить перед ней то,
            // что заведомо быстро, честнее к журналу службы: строка сторожа
            // появится раньше, чем строка раздачи.
            const stale = await closeStaleCalls(pool);
            if (stale.closed > 0) {
                console.log(`Планировщик: закрыто зависших звонков — ${stale.closed} (${stale.ids.join(', ')})`);
            }

            const result = await distributePendingLeads(pool);
            // СЛЕД ПИШЕТСЯ ТОЛЬКО КОГДА БЫЛА РАБОТА (ответ куратора И135).
            // Строка «тик прошёл» раз в минуту — это 1440 строк в сутки, в
            // которых потом не найти настоящую. А запись в app_settings или в
            // audit_log была бы хуже вдвойне: таблица настроек под триггером
            // журнала, и след засорил бы историю изменений навсегда.
            if (result && result.distributed > 0) {
                console.log(`Планировщик: роздано лидов — ${result.distributed}`);
            }
        } finally {
            await client.query('SELECT pg_advisory_unlock($1::bigint)', [LOCK_ID]);
        }
    } catch (err) {
        console.error('Планировщик: тик не отработал —', err.message);
    } finally {
        if (client) client.release();
    }
}

/** Запуск. Зовётся один раз при старте сервера, после накатки схемы. */
function start(pool) {
    if (!isEnabled()) {
        // Одна строка при старте, а не тишина: выключенный планировщик и
        // сломанный планировщик выглядят одинаково, и различить их должно быть
        // можно, не читая кода.
        console.log('Планировщик выключен: SCHEDULER_ENABLED не равен true');
        return false;
    }
    stopping = false;
    timer = setInterval(() => {
        // Предыдущий тик ещё идёт — пропускаем (К193).
        //
        // ПРИЗНАК ОБЯЗАН СБРАСЫВАТЬСЯ САМ. `stop()` обнуляет `current` только
        // при остановке; без `finally` планировщик отработал бы ровно один раз
        // и замолчал — причём молча, потому что в журнал он пишет, только когда
        // была работа.
        if (stopping || current) return;
        current = tick(pool).finally(() => { current = null; });
    }, TICK_MS);
    console.log(`Планировщик включён: тик раз в ${TICK_MS / 1000} с`);
    return true;
}

/**
 * Остановка. Ловится по SIGTERM, которым служба перезапускается при выкатке.
 *
 * Замок здесь ни при чём — сессионный снимется сам, когда оборвётся соединение.
 * Ждём мы другого: чтобы тик не оборвался ПОСЕРЕДИНЕ раздачи (ответ куратора
 * И134). Раздача идёт в транзакции и откатится целиком, но откат посреди выкатки
 * — это лид, которого выдали и тут же забрали, и оператор увидит его мигнувшим.
 */
async function stop() {
    stopping = true;
    if (timer) {
        clearInterval(timer);
        timer = null;
    }
    if (current) {
        try { await current; } catch (err) { /* тик и так не бросает */ }
        current = null;
    }
}

module.exports = { start, stop, isEnabled, TICK_MS, LOCK_ID };
