// «Звонки → События» объясняет, почему строка перевода видна и не работает, и
// отправляет человека чинить оффер в «CPA-сети» — значит обязана называть
// состояние ТЕМ ЖЕ СЛОВОМ, которым его называют там. Первое место — отказ
// сохранения оффера — держало ключи и подписи двумя параллельными массивами в
// самом маршруте. Второй список подписей был бы ровно К36, поэтому список
// переехал сюда, а не размножился (корректировка К229).
//
// ПЕРЕЧЕНЬ ОДИН И ТОТ ЖЕ ЧЕТЫРЁМ ЗНАЧЕНИЯМ КОЛОНКИ `real_estate_offers.status`
// (`schema.sql`, объявление таблицы). Порядок значим: он же порядок в тексте
// отказа — от рабочего состояния к нерабочим.

const OFFER_STATUSES = [
    ['active', 'Активен'],
    ['paused', 'На паузе'],
    ['disabled', 'Отключён'],
    ['draft', 'Черновик']
];

const STATUS_VALUES = OFFER_STATUSES.map(([value]) => value);
const STATUS_LABELS = OFFER_STATUSES.map(([, label]) => label);
const LABEL_BY_VALUE = Object.fromEntries(OFFER_STATUSES);

/**
 * Подпись состояния оффера.
 *
 * НЕИЗВЕСТНЫЙ КЛЮЧ ВОЗВРАЩАЕТСЯ КАК ЕСТЬ, а не заменяется прочерком: если в
 * колонке однажды окажется пятое значение, человек должен увидеть его, а не
 * пустоту, — иначе строка будет молча не работать без единого слова о причине.
 */
function offerStatusLabel(value) {
    return LABEL_BY_VALUE[value] || value;
}

module.exports = { OFFER_STATUSES, STATUS_VALUES, STATUS_LABELS, offerStatusLabel };
