// --- routes/pbxEvents.js: приём событий от АТС (этап Е1) ---------------------
//
// ЗАЧЕМ АДРЕС ЕСТЬ РАНЬШЕ, ЧЕМ ЕМУ ЕСТЬ ЧТО ДЕЛАТЬ. Адрес приёма прописывается
// на стороне станции, а не у нас. Он обязан существовать до того, как его туда
// впишут, иначе первая же настройка телефонии упрётся в 404 и будет выглядеть
// как поломка станции.
//
// ⚑ ЧТО ЗДЕСЬ ПОЯВИЛОСЬ В Е1. Прежде маршрут отвечал `503` и ничего не хранил —
// таблицы сырых сообщений ещё не было. Теперь есть всё трое: проверка секрета в
// адресе, рубильник приёма и само сохранение.
//
// ЧТЕНИЕ ФОРМАТА. Телфин шлёт события в `application/x-www-form-urlencoded` — и
// при GET, и при POST. Разбор подключён в `server.js`; без него тела приходили
// бы ПУСТЫМИ И БЕЗ ОШИБКИ: приложение честно отвечало бы «принято», записывало
// пустой звонок и не жаловалось (план 7.6).
//
// ТЕЛО СОБЫТИЯ НЕ ПОПАДАЕТ НИ В ОТВЕТ, НИ В ЖУРНАЛ СЛУЖБЫ. В нём едут номера
// звонивших — их место в базе под аудитом, а не в текстовом логе, который читают
// через `less` и копируют в переписку. Наружу уходят ЧИСЛА: сколько полей
// разобрано и завёлся ли звонок. Их достаточно, чтобы доказать работу приёма, и
// мало, чтобы что-нибудь утекло.
//
// МАРШРУТ СТОИТ ВНЕ КОНТЕКСТА АУДИТА (ответ куратора И130). Событие станции — не
// правка записи человеком, автора у него нет и взяться ему неоткуда.

const express = require('express');
const crypto = require('crypto');
const { pool } = require('../db');
const appSettings = require('../services/appSettings');
const pbxEventStore = require('../services/pbxEventStore');

const router = express.Router();

// ---------------------------------------------------------------- секрет в пути
//
// ⚠⚠ ПОДПИСИ У ЗАПРОСОВ ТЕЛФИНА НЕТ ВОВСЕ. Единственная защита — неугадываемый
// адрес, и документация прямо предостерегает (стр. 507) от адресов вида
// `/cid/807/queue/33334`: подобрав идентификаторы, посторонний сможет слать
// события. Секрет генерирует и вписывает на сервер куратор (решение 129), имя
// переменной занято им же 25.08.2026.
//
// ⚠ СРАВНЕНИЕ ПОСТОЯННОГО ВРЕМЕНИ. Обычное `===` выходит из сравнения на первом
// же несовпавшем знаке, и по времени ответа секрет подбирается знак за знаком.
// Через сеть это трудно, но защита стоит одной строки, а «трудно» — не «нельзя».
//
// ⚠⚠ ПУСТАЯ ПЕРЕМЕННАЯ ЗАКРЫВАЕТ ПРИЁМ, А НЕ ОТКРЫВАЕТ ЕГО ВСЕМ. Не задан
// секрет — не с чем сверять, и пускать в этом случае значит отдать адрес любому,
// кто его угадает. Ошибка настройки обязана падать в сторону отказа.
function tokenOk(given) {
    const expected = process.env.TELPHIN_EVENT_TOKEN || '';
    if (!expected) return false;
    const a = Buffer.from(String(given || ''), 'utf8');
    const b = Buffer.from(expected, 'utf8');
    // `timingSafeEqual` требует равной длины и сам бросает на разной — длину
    // сверяем заранее. Она и так утекает через размер запроса.
    if (a.length !== b.length) return false;
    return crypto.timingSafeEqual(a, b);
}

/**
 * Событие внутреннего номера.
 *
 * ОБА ГЛАГОЛА НА ОДНОМ АДРЕСЕ (ответ куратора И128): Телфин шлёт и GET, и POST —
 * это выбирается при подписке на событие и может отличаться от номера к номеру.
 * Требовать от настройщика попасть в единственный поддерживаемый глагол значит
 * заложить ошибку, которая проявится как «половина событий не доходит».
 */
router.all('/:token', async (req, res) => {
    // ⚠ НЕВЕРНЫЙ СЕКРЕТ ОТВЕЧАЕТ 404, А НЕ 403. Отказ «неверный токен» сообщает
    // подбирающему, что адрес существует и он на верном пути. Четыреста
    // четвёртый неотличим от несуществующего адреса — ровно то, чем защита и
    // держится.
    if (!tokenOk(req.params.token)) {
        return res.status(404).json({ error: 'Не найдено' });
    }

    // Считаем ОБЕ стороны: при GET поля едут в строке запроса, при POST — в теле.
    // Складывать их можно смело: станция шлёт что-то одно.
    const body = Object.assign({}, req.query || {}, req.body || {});

    let enabled;
    try {
        // ⚠ РУБИЛЬНИК ЖИВЁТ НАСТРОЙКОЙ (решение владельца 145): владелец гасит
        // поток сам и мгновенно, без правки файла на сервере и без перезапуска.
        // Умолчание при отсутствии строки — ВКЛЮЧЕНО: у этого выключателя опасно
        // бездействие, а не действие (довод целиком — в `schema.sql`).
        enabled = await appSettings.getBool(pool, 'pbx_events_enabled', true);
    } catch (err) {
        // ⚠⚠ БАЗА НЕДОСТУПНА — ОТВЕЧАЕМ ОТКАЗОМ, И ЭТО НАЗВАННЫЙ ВЫБОР, А НЕ
        // СЛУЧАЙНОСТЬ (ответ куратору до работы). Вопрос про рубильник здесь не
        // встаёт вовсе: без базы событие НЕКУДА ПОЛОЖИТЬ — хранение и есть база.
        // Ответить «принято» и выбросить хуже отказа: станция сочтёт сообщение
        // доставленным и не повторит, а потерянное событие звонка не
        // восстанавливается ничем.
        console.error('Приём событий: база недоступна —', err && err.code);
        return res.status(503).json({ error: 'Хранилище недоступно', code: 'storage_unavailable' });
    }

    if (!enabled) {
        // ⚠ ВЫКЛЮЧЕННЫЙ ПРИЁМ ТОЖЕ ОТВЕЧАЕТ ОТКАЗОМ, а не «принято». Рубильник
        // останавливает запись, а не делает вид, что она идёт; станция должна
        // знать, что сообщение не взято.
        return res.status(503).json({ error: 'Приём событий выключен', code: 'receiver_disabled' });
    }

    try {
        const result = await pbxEventStore.accept(pool, body);
        // Наружу — только числа. Значений полей здесь нет и не будет.
        return res.status(200).json({
            stored: true,
            fields: result.parsedFields,
            registered: result.registered
        });
    } catch (err) {
        // ⓘ Печатается КОД ошибки, а не она сама: в тексте ошибки драйвера лежат
        // параметры запроса, а среди них номера звонивших.
        console.error('Приём событий: сообщение не сохранено —', err && err.code);
        return res.status(500).json({ error: 'Не удалось сохранить событие' });
    }
});

module.exports = router;
