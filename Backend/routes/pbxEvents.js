// --- routes/pbxEvents.js: приём событий от АТС (часть 6, В1) ---
//
// ЗАЧЕМ АДРЕС ЕСТЬ РАНЬШЕ, ЧЕМ ЕМУ ЕСТЬ ЧТО ДЕЛАТЬ. Адрес приёма прописывается
// на стороне станции, а не у нас. Он обязан существовать до того, как его туда
// впишут, иначе первая же настройка телефонии упрётся в 404 и будет выглядеть
// как поломка станции.
//
// ЧТО ЗДЕСЬ ЕСТЬ И ЧЕГО НЕТ. Есть чтение формата: Телфин шлёт события в
// `application/x-www-form-urlencoded` — и при GET, и при POST, — а сервер до
// этой части умел только JSON. Тела приходили бы ПУСТЫМИ И БЕЗ ОШИБКИ:
// приложение честно отвечало бы «принято», записывало пустой звонок и не
// жаловалось (план 7.6).
//
// Нет хранения: таблица сырых сообщений заводится частью 7 (план Г2). Поэтому
// маршрут отвечает 503, а не 200 — ответ куратора И127. Молча выбросить событие
// хуже всего: станция сочтёт его принятым и не повторит, а потерянное событие
// звонка не восстанавливается ничем.
//
// ТЕЛО СОБЫТИЯ НЕ ПОПАДАЕТ НИ В ОТВЕТ, НИ В ЖУРНАЛ СЛУЖБЫ. В нём едут номера
// звонивших — их место в базе под аудитом, а не в текстовом логе, который читают
// через `less` и копируют в переписку. Наружу уходит ОДНО ЧИСЛО: сколько полей
// удалось разобрать. Его достаточно, чтобы доказать, что разбор формата работает
// (разобрал восемь — значит `urlencoded` подключён; ноль — значит нет), и мало,
// чтобы что-нибудь утечь.
//
// ПРОВЕРКИ ТОКЕНА ЗДЕСЬ ПОКА НЕТ, И ЭТО НАЗВАНО ВСЛУХ. Подписи у запросов
// Телфина нет вовсе, единственная защита — неугадываемый адрес, и документация
// прямо советует случайный токен в пути (стр. 507). Сам токен — секрет, значит
// живёт в переменных окружения — имя занято куратором 25.08.2026:
// `TELPHIN_EVENT_TOKEN`, в семью к `TELPHIN_APP_ID` и `TELPHIN_API_BASE`. Пока
// маршрут не хранит ничего и всем отвечает одинаково, сверять токен не с чем:
// защищать нечего. Сверка появляется в той же части, где появляется хранение, —
// вместе с именем переменной.
//
// МАРШРУТ СТОИТ ВНЕ КОНТЕКСТА АУДИТА (ответ куратора И130). Событие станции — не
// правка записи человеком, автора у него нет и взяться ему неоткуда.

const express = require('express');

const router = express.Router();

/**
 * Событие внутреннего номера.
 *
 * ОБА ГЛАГОЛА НА ОДНОМ АДРЕСЕ (ответ куратора И128): Телфин шлёт и GET, и POST —
 * это выбирается при подписке на событие и может отличаться от номера к номеру.
 * Требовать от настройщика попасть в единственный поддерживаемый глагол значит
 * заложить ошибку, которая проявится как «половина событий не доходит».
 */
router.all('/:token', (req, res) => {
    // Считаем ОБЕ стороны: при GET поля едут в строке запроса, при POST — в теле.
    // Складывать их можно смело: станция шлёт что-то одно.
    const fields = Object.keys(req.query || {}).length + Object.keys(req.body || {}).length;

    res.status(503).json({
        error: 'Приёмник событий ещё не готов',
        code: 'receiver_not_ready',
        // Единственное, что уходит наружу. Значений полей здесь нет и не будет.
        fields
    });
});

module.exports = router;
