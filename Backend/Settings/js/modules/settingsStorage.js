// --- Settings/js/modules/settingsStorage.js: запросы экрана настроек -------
//
// Правило проекта: прямых fetch вне storage-модуля нет. Транспорт приходит
// параметром — это ctx.api оболочки, привязанный к жизни панели.
//
// ЗАПРОСОВ РОВНО ДВА, И ВТОРОГО «СОХРАНИТЬ ВСЁ» НЕ БУДЕТ. Настройки не форма:
// между ними нет связи, и общая кнопка означала бы, что опечатка в пороге
// сторожа откатывает правку рабочего окна. Второй довод сильнее первого —
// журнал изменений: одна правка это одна строка с понятным смыслом, а
// «сохранено 7 настроек» в разборе «почему всё сломалось в четверг» не значит
// ничего (паспорт Р8).

/** Весь список. Порядок задан сервером — `group_order`, и пересортировке не подлежит. */
export function fetchSettings(api) {
    return api.get('/settings');
}

/** Одна настройка. Ключ в адресе, значение в теле — строкой, как оно лежит в базе. */
export function saveSetting(api, key, value) {
    return api.put(`/settings/${encodeURIComponent(key)}`, { value });
}

/**
 * Ключ телефонии. ⚠ СВОЯ ДВЕРЬ, А НЕ ВЕТКА В ОБЩЕЙ: за ней другое хранилище
 * (`pbx_credentials`, исключена из журнала) и другое правило ответа —
 * значение обратно НЕ ПРИХОДИТ, приходит только признак «задано».
 * ⚠ Пустое значение здесь законно: это очистка ключа, а не ошибка ввода.
 */
export function saveSecret(api, key, value) {
    return api.put(`/settings/secret/${encodeURIComponent(key)}`, { value });
}
