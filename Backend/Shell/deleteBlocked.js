// --- deleteBlocked.js: окно «Нельзя удалить», одно на пять разделов ---------
//
// ОДНО ОКНО, А НЕ ПЯТЬ (ответ на И118). Кнопки удаления живут в пяти разделах —
// «CPA-сети», объекты недвижимости, «Скрипты», «Источники», «Лиды», — и окно у
// них одно и то же по устройству: заголовок, что мешает числами, что сделать,
// одна кнопка. Пять копий разошлись бы на первой же правке текста.
//
// ЭКРАН НЕ РЕШАЕТ, МОЖНО ЛИ УДАЛЯТЬ, и не считает помехи. Решает сервер по
// правилам плана 11.4; сюда приезжает готовый разбор — пары «сколько — чего» с
// машинным кодом. Транспорт оболочки проносит их наружу полем `blockers`
// (api.js), поэтому разбирать готовую фразу не приходится.

import { plural as obshchiyPlural } from '/plural.js';
import { openModal } from '/ui/modal.js';

// СКЛОНЕНИЕ ЖИВЁТ ЗДЕСЬ, И ЭТО НЕ САМОДЕЯТЕЛЬНОСТЬ, а прямое требование
// паспорта Р7: «текст собирает экран — иначе перевод и склонение окажутся в
// бэкенде». Сервер отдаёт слово в ИМЕНИТЕЛЬНОМ МНОЖЕСТВЕННОГО («объекты
// недвижимости»), потому что число едет отдельным полем и склеивать их на
// сервере значило бы выбирать за экран падеж. Макет 2c0535d0 показывает
// готовую фразу склонённой — «12 объектов недвижимости», «4 источника», — и
// собрать её может только тот, кто знает и число, и слово разом. Это здесь.
//
// Три формы на вид помехи: 1 · 2–4 · 5 и больше. Порядок тот же, что у
// KIND_ORDER на сервере, чтобы два списка читались рядом.
const WORDS = {
    documents: ['документ', 'документа', 'документов'],
    calls: ['звонок', 'звонка', 'звонков'],
    schedule_days: ['день графика', 'дня графика', 'дней графика'],
    leads: ['лид', 'лида', 'лидов'],
    wrapup_target: [
        'событие «Пост-обработка», где он выбран статусом после тайм-аута',
        'события «Пост-обработка», где он выбран статусом после тайм-аута',
        'событий «Пост-обработка», где он выбран статусом после тайм-аута'
    ],
    script_pairs: ['набор «скрипт + статус»', 'набора «скрипт + статус»', 'наборов «скрипт + статус»'],
    recall_rules: ['правило автоперезвона', 'правила автоперезвона', 'правил автоперезвона'],
    recall_targets: [
        'правило, где он выбран статусом после предела',
        'правила, где он выбран статусом после предела',
        'правил, где он выбран статусом после предела'
    ],
    merged_leads: ['влитый дубль', 'влитых дубля', 'влитых дублей'],
    offers: ['объект недвижимости', 'объекта недвижимости', 'объектов недвижимости'],
    sources: ['источник', 'источника', 'источников'],
    cpa_networks: ['CPA-сеть', 'CPA-сети', 'CPA-сетей'],
    departments: ['отдел', 'отдела', 'отделов'],
    bank_accounts: ['банковский счёт', 'банковских счёта', 'банковских счетов'],
    taxes: ['налог', 'налога', 'налогов']
};

/**
 * Слово помехи в падеже, которого требует число.
 *
 * НЕИЗВЕСТНЫЙ ВИД НЕ ЛОМАЕТ ОКНО: берётся `what` с сервера как есть. Он всегда
 * есть и всегда осмыслен — просто в именительном. Новая помеха, заведённая на
 * сервере (например, звонки в части 7), покажется сразу, а склонение ей
 * допишут здесь одной строкой.
 */
function plural(kind, count, fallback) {
    const forms = WORDS[kind];
    if (!forms) return fallback || kind || '';
    // ⚠ `Math.abs` ОСТАЁТСЯ ЗДЕСЬ, А НЕ УХОДИТ В ОБЩИЙ ПОМОЩНИК (К308).
    // Он был только у этой копии: остальные шесть на отрицательном числе
    // дают форму множественного. Отрицательных помех не бывает, но
    // сведение не вправе менять поведение молча — местная особенность
    // остаётся у места, где она была.
    return obshchiyPlural(Math.abs(Number(count)), forms[0], forms[1], forms[2]);
}

/**
 * Показывает окно отказа.
 *
 * СКЛОНЕНИЕ ТОГО, ЧТО УДАЛЯЮТ, ОСТАЁТСЯ У РАЗДЕЛА. «К сети привязано…» и
 * «…тогда сеть удалится» — два падежа одного существительного, и раздел
 * передаёт обе фразы целиком. Собирать их здесь значило бы завести в общем
 * файле вторую таблицу склонений — на семь сущностей вместо помех.
 *
 * @param {Object}      opts
 * @param {HTMLElement} [opts.scope]   панель раздела, которую надо накрыть
 * @param {string}      opts.sub       что пытались удалить, с именем
 * @param {string}      opts.lead      абзац перед списком
 * @param {string}      opts.tail      абзац после списка: что сделать
 * @param {Array}       opts.blockers  помехи с сервера: { kind, what, count }
 * @returns {Object} окно слоя
 */
export function openDeleteBlocked({ scope = null, sub = '', lead = '', tail = '', blockers = [] }) {
    // Фрагментом, а не обёрткой: в макете абзацы и список — прямые дети
    // .ui-modal__body, и лишний слой сбил бы их отступы.
    const body = document.createDocumentFragment();

    if (lead) {
        const p = document.createElement('p');
        p.textContent = lead;
        body.appendChild(p);
    }

    const list = document.createElement('div');
    list.className = 'arc-block';
    // ПОРЯДОК НЕ ТРОГАЕМ. Сервер уже разложил помехи от невосполнимого к
    // восполнимому (deleteGuards.KIND_ORDER); пересортировать их здесь значит
    // завести вторую очередь важности и разойтись с ней.
    for (const b of blockers) {
        const row = document.createElement('div');
        row.className = 'arc-block__row';

        const count = document.createElement('span');
        count.className = 'arc-block__count';
        count.textContent = String(b.count);

        const what = document.createElement('span');
        what.className = 'arc-block__what';
        what.textContent = plural(b.kind, b.count, b.what);

        row.append(count, what);
        list.appendChild(row);
    }
    body.appendChild(list);

    if (tail) {
        const p = document.createElement('p');
        p.textContent = tail;
        body.appendChild(p);
    }

    // КНОПКА НЕ «ОТМЕНА», А «ПОНЯТНО»: отменять нечего, ничего не начиналось и
    // удаление не состоялось. Она же получает фокус — она в окне одна.
    return openModal({
        title: 'Нельзя удалить',
        sub,
        body,
        scope,
        size: 'narrow',
        actions: [{ label: 'Понятно', autofocus: true, value: 'ok' }]
    });
}

/**
 * Разбирает ошибку транспорта: это отказ по помехам или что-то другое?
 *
 * Разделы зовут её в catch, чтобы не проверять два поля в пяти местах. Признак
 * — код `delete_blocked`, а не наличие `blockers`: пустой список помех окном не
 * показывается вовсе (паспорт: «не бывает пустым»), и по одному лишь массиву
 * отличить отказ от чего-то ещё нельзя.
 */
export function isDeleteBlocked(err) {
    return Boolean(err && err.code === 'delete_blocked'
        && Array.isArray(err.blockers) && err.blockers.length > 0);
}
