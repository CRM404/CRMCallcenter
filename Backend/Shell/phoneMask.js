// Живая маска «+7 (___) ___-__-__» — только российский формат (design-решение,
// report_designer.md, «правки по фидбеку владельца», 12.08.2026).
function maskRuPhone(raw) {
    let d = raw.replace(/\D/g, '');
    if (d.startsWith('8')) d = '7' + d.slice(1);
    if (!d.startsWith('7')) d = '7' + d;
    d = d.slice(0, 11);
    let out = '+7';
    if (d.length > 1) out += ' (' + d.slice(1, 4);
    if (d.length >= 4) out += ')';
    if (d.length > 4) out += ' ' + d.slice(4, 7);
    if (d.length > 7) out += '-' + d.slice(7, 9);
    if (d.length > 9) out += '-' + d.slice(9, 11);
    return out;
}

// ⚠⚠ ОБЁРТОК ДВЕ, И ВТОРАЯ ЗАВЕДЕНА НЕ ОТ ЛЕНИ СВЕСТИ ИХ В ОДНУ.
// `wireRuPhoneMask` (ниже) применяется там, где поле принимает ТОЛЬКО внешний
// номер: карточка лида в «Лидах». Там маска верна всегда, и трогать её нельзя.
// `wireDialMask` (следом) применяется в пульте оператора, где решение владельца
// 147 требует набирать И внешние, И внутренние: «давай сделаем сразу чтобы можно
// было вписывать и набирать реальные номера и вписывать и набирать добавочные».
//
// ⛔ ПОЧЕМУ ОДНОЙ ФУНКЦИЕЙ НЕ ОБОЙТИСЬ. `maskRuPhone` дописывает семёрку всему,
// что с семёрки не начинается (строка `if (!d.startsWith('7'))` выше), и ввод
// `101` превращается в `+7 (101)`. Это не «маска немного мешает» — внутренний
// вызов становится невозможен в принципе, а сервер увидит четыре цифры вместо
// трёх и сочтёт номер внешним.
//
// ⚠ ЕДИНОГО ПОВЕДЕНИЯ ЗДЕСЬ БЫТЬ НЕ МОЖЕТ: одно и то же поле в двух местах
// принимает разное. Свести их значило бы отдать «Лидам» правило, которого они не
// просили, — и разошлись бы они молча, как разошлись три показа телефона.

// Длина внутреннего номера — замер станции (префикс `16780`, длина 3), тот же,
// что у разбора на сервере (`services/pbxDial.js`, INTERNAL_LEN).
const INTERNAL_LEN = 3;

/**
 * Нужна ли маска этому вводу.
 *
 * ПРАВИЛО ПОЛЯ (решение владельца 147): маска включается, когда цифр больше
 * трёх ИЛИ первая цифра `7` либо `8`. До этого ввод свободный.
 *
 * ⚠ ДВЕ ПОЛОВИНЫ ПРАВИЛА ПРО РАЗНОЕ, И ОБЕ НУЖНЫ. Первая пропускает добавочный
 * (`101`, `099`, `000` — три цифры, свободно) и включает маску на четвёртой
 * цифре городского без кода страны (`9991234567`). Вторая ловит номер,
 * начатый со страны (`8…`, `7…`): там маска нужна с первого знака, а по числу
 * цифр она включилась бы только с четвёртого.
 */
function needsMask(digits) {
    if (digits.length > INTERNAL_LEN) return true;
    return digits[0] === '7' || digits[0] === '8';
}

/**
 * Навесить маску пульта: внешние номера — под маску, добавочные — свободно.
 *
 * ⚠ ПОКА МАСКА НЕ ВКЛЮЧИЛАСЬ, ПОЛЕ НЕ ТРОГАЕТСЯ ВОВСЕ — ни чистки от букв, ни
 * подстановки. Свободный ввод и значит свободный: судит о номере сервер
 * (`services/pbxDial.js`), и подмена на стороне экрана лишила бы его
 * единственного честного входа — того, что человек набрал.
 *
 * @param {HTMLInputElement} input поле номера в пульте
 */
export function wireDialMask(input) {
    if (!input) return;
    input.addEventListener('input', (e) => {
        const digits = e.target.value.replace(/\D/g, '');
        if (!needsMask(digits)) return;
        const pos = e.target.selectionStart;
        const before = e.target.value.length;
        e.target.value = maskRuPhone(e.target.value);
        const after = e.target.value.length;
        e.target.selectionEnd = Math.max(0, pos + (after - before));
    });
}

/**
 * Навесить маску на поле ввода. Каретка возвращается на место: маска
 * дописывает разделители, и без поправки на разницу длин курсор уезжал бы
 * в конец строки на каждом знаке.
 *
 * @param {HTMLInputElement} input поле номера
 */
export function wireRuPhoneMask(input) {
    if (!input) return;
    input.addEventListener('input', (e) => {
        const pos = e.target.selectionStart;
        const before = e.target.value.length;
        e.target.value = maskRuPhone(e.target.value);
        const after = e.target.value.length;
        e.target.selectionEnd = Math.max(0, pos + (after - before));
    });
}
