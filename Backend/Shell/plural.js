/**
 * Русское склонение существительного при числе — ОДНО на весь проект (К308).
 *
 * ЗАЧЕМ ЗАВЕДЁН. До этой правки помощник был объявлен СЕМЬ раз в семи файлах —
 * «Звонки», CPA, «Сотрудники», «Источники», история изменений, окно отказа
 * оболочки и список скриптов. Двенадцать объявлений вместе с обёртками.
 * Экспортировался ровно один — из `employeesScheduleTime.js`, то есть лежал
 * внутри раздела «Сотрудники»: тянуть его в «Лиды» значило бы завести связь
 * между разделами ради числительного.
 *
 * ПОЧЕМУ ЗДЕСЬ, А НЕ В `ui/`. В `Shell/ui/` живут узлы ВИДА — окно, чип,
 * складка, таблица. Склонение — работа с текстом, а не элемент интерфейса.
 * Место ему рядом с `api.js` и `viewPrefs.js`: это общие утилиты оболочки,
 * которые разделы зовут корневым путём (`import { plural } from '/plural.js'`).
 *
 * ⚠ СВЕДЕНИЕ НИ ОДНОЙ НАДПИСИ НЕ ИЗМЕНИЛО, и это замер, а не надежда. Три
 * разных тела ходили по проекту:
 *   А — `mod10 === 1 && mod100 !== 11` … (Звонки, история изменений);
 *   Б — `tens >= 11 && tens <= 14` … (CPA, Источники, окно отказа);
 *   В — `tens > 10 && tens < 20` … (Сотрудники).
 * Все три прогнаны на числах 0…1000 — расхождений НОЛЬ. Отдельно прогнаны
 * `deleteBlocked` (15 видов помех × 301 число = 4515 случаев) и
 * `pluralObjections` (1001 число) — тоже ноль. Прибор при этом доказан:
 * подсунутый заведомо неверный помощник дал расхождения на всех числах.
 *
 * ⚠ ПРАВИЛО, КОТОРОЕ НЕ ЗАПИСЫВАЛОСЬ, А ДЕЙСТВОВАЛО. У «Источников» в одном
 * сообщении стоят оба приёма сразу: предмет счёта идёт родительным без
 * склонения («источников: N»), побочное число — через помощника («на них N
 * лидов»). Значит вопрос не «склонять или нет», а:
 *   предмет счёта — родительный падеж;
 *   побочное число в фразе — помощник.
 *
 * @param {number} n     число, при котором стоит слово
 * @param {string} one   форма для 1, 21, 31 … («оффер», «день», «смена»)
 * @param {string} few   форма для 2–4, 22–24 … («оффера», «дня», «смены»)
 * @param {string} many  форма для 5–20, 11–14 и прочих («офферов», «дней»)
 * @returns {string} форма слова — БЕЗ самого числа: его подставляет вызывающий
 *
 * @example
 *   `${n} ${plural(n, 'оффер', 'оффера', 'офферов')}`  // «3 оффера»
 */
export function plural(n, one, few, many) {
    const tens = n % 100;
    if (tens >= 11 && tens <= 14) return many;
    const ones = n % 10;
    if (ones === 1) return one;
    if (ones >= 2 && ones <= 4) return few;
    return many;
}
