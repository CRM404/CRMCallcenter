-- ============================================================
-- Нормализация «Срока сдачи» под справочник deadline
-- Готовит исполнитель, ВЫПОЛНЯЕТ ВЛАДЕЛЕЦ на боевой базе
-- (прямого доступа на запись у сессии нет), 14.08.2026.
-- ============================================================
--
-- Зачем. С этой задачи «Срок сдачи» у лида выбирается из справочника
-- (param_lists, ключ deadline): «Сдан» + кварталы «1 кв. 2026» … «4 кв. 2029».
-- У офферов то же поле заполнялось руками, и на бою накопилось десять разных
-- написаний одного и того же квартала. Пока написания не сведены к одному,
-- будущая сверка «оффер сдаётся не позже, чем нужно клиенту» сравнивать их не
-- сможет: она идёт по порядку значений справочника, а «4кв. 2027» в справочнике
-- нет — есть «4 кв. 2027».
--
-- Что делает скрипт: приводит написания к каноническим. Значения, которых нет
-- в списке ниже, НЕ трогает — в конце скрипт покажет всё, что осталось
-- ненормализованным, чтобы это не потерялось молча.
--
-- Как выполнять: целиком, одной транзакцией. Первый SELECT — предпросмотр
-- («что и во что превратится»), его можно прогнать отдельно ДО изменения.
--
-- ВНИМАНИЕ, одно значение спорное: « 2-4 кв. 2028 года.» — это диапазон, а не
-- квартал. Скрипт приводит его к ПОЗДНЕМУ краю (4 кв. 2028): для сверки «не
-- позже» безопаснее пообещать более поздний срок, чем более ранний. Если по
-- факту дом сдаётся во 2 кв. 2028 — поправьте значение вручную.

BEGIN;

-- 1. Предпросмотр: что именно будет изменено
SELECT 'real_estate_offers' AS "таблица", deadline AS "было", count(*)::int AS "строк"
FROM real_estate_offers
WHERE deadline IS NOT NULL
GROUP BY deadline
UNION ALL
SELECT 'leads', delivery_deadline, count(*)::int
FROM leads
WHERE delivery_deadline IS NOT NULL
GROUP BY delivery_deadline
ORDER BY 1, 2;

-- 2. Нормализация. Список написаний — фактический с боевой базы (39 офферов,
-- десять вариантов). btrim снимает ведущие/хвостовые пробелы, поэтому вариант
-- с пробелом в начале ловится тем же условием.
UPDATE real_estate_offers SET deadline = CASE btrim(deadline)
    WHEN 'Сдан'              THEN 'Сдан'
    WHEN '4кв. 2027'         THEN '4 кв. 2027'
    WHEN '3 кв. 2028'        THEN '3 кв. 2028'
    WHEN '4 кв. 2026 г.'     THEN '4 кв. 2026'
    WHEN '3 квартал 2027'    THEN '3 кв. 2027'
    WHEN '3 кв. 2027'        THEN '3 кв. 2027'
    WHEN '3 кв. 2027 г.'     THEN '3 кв. 2027'
    WHEN '4 кв. 2028'        THEN '4 кв. 2028'
    WHEN '2-4 кв. 2028 года.' THEN '4 кв. 2028'  -- диапазон → поздний край, см. примечание выше
    WHEN '2 кв 2027г'        THEN '2 кв. 2027'
    ELSE deadline
END
WHERE deadline IS NOT NULL;

-- Те же написания могли попасть и к лидам (поле заполнялось текстом до
-- появления справочника). Если таких значений нет — запрос просто ничего не
-- изменит; на боевой базе значений лидов не видно, поэтому включено «на всякий».
UPDATE leads SET delivery_deadline = CASE btrim(delivery_deadline)
    WHEN 'Сдан'              THEN 'Сдан'
    WHEN '4кв. 2027'         THEN '4 кв. 2027'
    WHEN '3 кв. 2028'        THEN '3 кв. 2028'
    WHEN '4 кв. 2026 г.'     THEN '4 кв. 2026'
    WHEN '3 квартал 2027'    THEN '3 кв. 2027'
    WHEN '3 кв. 2027'        THEN '3 кв. 2027'
    WHEN '3 кв. 2027 г.'     THEN '3 кв. 2027'
    WHEN '4 кв. 2028'        THEN '4 кв. 2028'
    WHEN '2-4 кв. 2028 года.' THEN '4 кв. 2028'
    WHEN '2 кв 2027г'        THEN '2 кв. 2027'
    ELSE delivery_deadline
END
WHERE delivery_deadline IS NOT NULL;

-- 3. Что осталось вне справочника. Пустой результат = всё сведено.
-- Непустой — не ошибка скрипта: значит, на бою появились написания, которых на
-- момент подготовки не было. Их можно либо поправить руками, либо добавить в
-- справочник через «Настройку списков».
SELECT 'real_estate_offers' AS "таблица", deadline AS "осталось вне справочника", count(*)::int AS "строк"
FROM real_estate_offers
WHERE deadline IS NOT NULL
  AND deadline NOT IN (SELECT value FROM param_lists WHERE list_key = 'deadline')
GROUP BY deadline
UNION ALL
SELECT 'leads', delivery_deadline, count(*)::int
FROM leads
WHERE delivery_deadline IS NOT NULL
  AND delivery_deadline NOT IN (SELECT value FROM param_lists WHERE list_key = 'deadline')
GROUP BY delivery_deadline
ORDER BY 1, 2;

COMMIT;

-- Если последний SELECT показал что-то неожиданное и менять не хочется —
-- вместо COMMIT выполните ROLLBACK, изменений не останется.
